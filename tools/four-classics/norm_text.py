def repl_only(s):
    for a, b in REPL_MULTI + REPL_ONE:
        s = s.replace(a, b)
    return s


def fix_text(text, book, name):
    t = repl_only(text)
    t = t.replace("沉琳", "沈琳")
    t = t.replace(" ", "")
    if name == "九宫八风":
        t = nine_palace(t)
    if name in ("刺法论", "本病论"):
        t = NL.join(l for l in t.split(NL) if not l.strip().startswith("素问•"))
        t = t.replace("(遗篇)", "（遗篇）")
    if name == "针解篇":
        t = t.replace("*", "")
    if name == "本神":
        t = t.replace("==", "")
    if name == "经脉":
        t = t.replace("〈硫，目代石〉", "").replace("〈疒贵〉", "")
    if book in ("伤寒论", "金匮要略"):
        t = colons(t, name)
    if name == "中风历节病脉证并治第五":
        t = t.replace("防风十分人参三分", "防风十分　人参三分")
        t = t.replace("川乌五枚㕮咀", "川乌五枚（㕮咀")
    if name == "果实菜谷禁忌并治第二十五":
        t = NL.join(l for l in t.split(NL) if not l.strip().startswith("Category:"))
    return t


def nine_palace(t):
    i = t.find("{|")
    j = t.find("|}", i + 1) if i >= 0 else -1
    if i >= 0 and j > i:
        table = NL.join([
            "**合八风虚实邪正**",
            "",
            "| 立夏 四巽 阴洛 东南方 | 夏至 九离 上天 南方 | 立秋 二坤 玄委 西南方 |",
            "| --- | --- | --- |",
            "| 春分 三震 仓门 东方 | 招摇 五 中央 | 秋分 七兑 仓果 西方 |",
            "| 立春 八艮 天留 东北方 | 冬至 一坎 叶蛰 北方 | 立冬 六乾 新洛 西北方 |",
        ])
        t = t[:i] + table + t[j + 2:]
    return t


def colons(t, name):
    """底本以「::」标记方剂组成、方后注等行；「::;」与单「:」为方名行，转作【方名】。

    阳明篇另有串入的后世方解注文（君臣佐使串字），截去。
    """
    out = []
    for line in t.split(NL):
        s = line.strip()
        if s.startswith("::;"):
            s = "【" + s[3:] + "】"
        elif s.startswith("::"):
            s = s[2:]
        elif s.startswith(":"):
            s = "【" + s[1:] + "】"
        if name.startswith("辨阳明") and "(君)" in s:
            s = s.split("(君)")[0].rstrip()
        out.append(s)
    return NL.join(out)


